#!/usr/bin/env node
/**
 * Generates VERIFICATION_REPORT.md — the internal dashboard for closing the
 * remaining evidence gaps.
 *
 * It is deliberately unflattering. It reports how many credentials a stranger
 * can actually check without asking Gabriel for anything, and names every one
 * that they cannot.
 *
 *   node scripts/gen-verification-report.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const doc = JSON.parse(readFileSync(join(process.cwd(), "data", "credentials.json"), "utf8"));
const creds = doc.credentials;
const registries = doc._meta.registries;

const live = (c) => {
  if (c.verify_status === "pending") return null;
  if (c.verify_url) return c.verify_url;
  if (c.registry) return registries[c.registry]?.url ?? null;
  return null;
};

const gated = creds.filter((c) => c.feature_flag);
// Coursework-only records assert that NO degree was conferred, so they need no
// verification route. Counting them as unverifiable would penalise the site for
// disclosing them, which is exactly backwards.
const active = creds.filter(
  (c) => !c.feature_flag && c.category !== "coursework_not_conferred",
);
const disclosures = creds.filter((c) => c.category === "coursework_not_conferred");

const verified = active.filter((c) => live(c));
const noRegistry = active.filter((c) => !live(c) && c.no_public_registry);
const pending = active.filter((c) => c.verify_status === "pending");
const other = active.filter((c) => !live(c) && !c.no_public_registry && c.verify_status !== "pending");

const pct = (n) => `${Math.round((n / active.length) * 100)}%`;

const key = (c) => c.dual_issue_group ?? c.id;
const uni = active.filter((c) => c.counts_as_university_degree);
const argentine = uni.filter((c) => c.registry === "registrograduados");
const international = uni.filter((c) => c.registry !== "registrograduados");
const programmes = new Set(uni.map(key)).size;

const todos = creds
  .filter((c) => typeof c.internal_note === "string" && c.internal_note.includes("TODO(gabriel)"))
  .map((c) => ({ id: c.id, note: c.internal_note }));

const gaps = doc._meta.accepted_gaps ?? [];

const row = (c) => {
  const t = c.title_en ?? c.title_es;
  const url = live(c);
  const how = url
    ? `[verify](${url})`
    : c.verify_status === "pending"
      ? "**pending**"
      : c.no_public_registry
        ? "no public registry"
        : "**UNROUTED**";
  return `| \`${c.id}\` | ${t} | ${c.institution} | ${c.conferred ?? "—"} | ${how} |`;
};

const lines = [];
const out = (s = "") => lines.push(s);

out("# Verification report");
out();
out(`Generated by \`scripts/gen-verification-report.mjs\` from \`data/credentials.json\`.`);
out(`Do not edit by hand — run \`npm run report\` instead.`);
out();
out(`**Source data generated:** ${doc._meta.generated}`);
out();
out("## Headline");
out();
out(`- **${active.length}** credential claims published.`);
out(`- **${verified.length}** (${pct(verified.length)}) have a live third-party verification route a stranger can click today.`);
out(`- **${noRegistry.length}** (${pct(noRegistry.length)}) carry an explicit "no public registry exists" acknowledgement.`);
out(`- **${pending.length}** (${pct(pending.length)}) are awaiting a verification URL — **these are the gaps to close.**`);
if (other.length) out(`- **${other.length}** are unrouted and should not be published. Fix immediately.`);
if (gated.length) out(`- **${gated.length}** hidden behind a feature flag pending confirmation.`);
if (disclosures.length) {
  out(
    `- **${disclosures.length}** additional records are published as disclosures rather than claims ` +
      `(coursework completed, no degree conferred). They need no verification route and are excluded from the figures above.`,
  );
}
out();
out("## Degree counts, as published");
out();
out(`| Figure | Value |`);
out(`| --- | ---: |`);
out(`| University degrees in Argentina's national registry | ${argentine.length} |`);
out(`| International degree titles issued | ${international.length} |`);
out(`| International degree programmes (dual-issued counted once) | ${new Set(international.map(key)).size} |`);
out(`| **Distinct university degree programmes** | **${programmes}** |`);
out(`| Non-university tertiary titles | ${active.filter((c) => c.category === "tertiary_non_university").length} |`);
out(`| Legal admissions | ${active.filter((c) => c.category === "legal_admission").length} |`);
out(`| Professional licences | ${active.filter((c) => c.category === "professional_licence").length} |`);
out(`| Professional certifications | ${active.filter((c) => c.category === "certification" && c.cert_kind === "professional").length} |`);
out(`| Coursework completed, no degree conferred (excluded from all counts) | ${active.filter((c) => c.category === "coursework_not_conferred").length} |`);
out();

if (pending.length) {
  out("## Gaps to close — verification pending");
  out();
  out("Each of these has an issuer-verified badge that exists but whose public URL has not been published. Paste the URL into `data/credentials.json` and it renders automatically.");
  out();
  out("| id | Credential | What is needed |");
  out("| --- | --- | --- |");
  for (const c of pending) {
    out(`| \`${c.id}\` | ${c.title_en ?? c.title_es} | ${(c.internal_note ?? "").replace(/^TODO\(gabriel\): /, "")} |`);
  }
  out();
}

if (other.length) {
  out("## ⚠ Unrouted credentials");
  out();
  out("These are published with no verification route and no acknowledgement. This is exactly the failure mode the whole system exists to prevent.");
  out();
  for (const c of other) out(`- \`${c.id}\` — ${c.title_en ?? c.title_es}`);
  out();
}

out("## Full inventory");
out();
const order = [
  ["legal_admission", "Legal admissions"],
  ["professional_licence", "Professional licences"],
  ["doctorate", "Doctorate"],
  ["postgraduate_international", "Postgraduate (international)"],
  ["postgraduate_argentina", "Postgraduate (Argentina)"],
  ["undergraduate", "University degrees (grado / pregrado)"],
  ["tertiary_non_university", "Non-university tertiary"],
  ["certification", "Certifications"],
  ["coursework_not_conferred", "Coursework only — not degrees"],
];
for (const [cat, label] of order) {
  const group = creds.filter((c) => c.category === cat);
  if (!group.length) continue;
  out(`### ${label} (${group.filter((c) => !c.feature_flag).length})`);
  out();
  out("| id | Credential | Institution | Conferred | Verification |");
  out("| --- | --- | --- | --- | --- |");
  for (const c of group) out(row(c));
  out();
}

if (gated.length) {
  out("## Behind a feature flag");
  out();
  for (const c of gated) {
    out(`- \`${c.id}\` — ${c.title_en ?? c.title_es}. Flag: \`${c.feature_flag}\`. ${c.internal_note ?? ""}`);
  }
  out();
}

if (gaps.length) {
  out("## Accepted data gaps");
  out();
  out("Known and tracked. The validator fails the build on any NEW gap, but tolerates these.");
  out();
  for (const g of gaps) out(`- \`${g.id}\`.\`${g.field}\` — ${g.reason} ${g.todo}`);
  out();
}

if (todos.length) {
  out("## Open TODOs");
  out();
  for (const t of todos) out(`- \`${t.id}\` — ${t.note}`);
  out();
}

if (doc.unevidenced_claims_removed?.length) {
  out("## Claims removed for lack of evidence");
  out();
  out("Each of these was live on a public page and could not be substantiated. Supplying a credential ID restores any of them.");
  out();
  for (const r of doc.unevidenced_claims_removed) {
    out(`### ${r.claim}`);
    out();
    out(`- **Where it appeared:** ${r.where}`);
    out(`- **Finding:** ${r.finding}`);
    out(`- **Action:** ${r.action}`);
    out();
  }
}

writeFileSync(join(process.cwd(), "VERIFICATION_REPORT.md"), lines.join("\n"), "utf8");
console.log(
  `✓ VERIFICATION_REPORT.md written — ${verified.length}/${active.length} credentials independently verifiable (${pct(verified.length)}).`,
);
